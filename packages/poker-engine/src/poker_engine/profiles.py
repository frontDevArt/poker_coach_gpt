"""Диапазон соперника по наблюдённому VPIP.

Клиент GG печатает VPIP бейджем у аватара: доля раздач, в которых игрок
добровольно вложил деньги на префлопе коллом или рейзом. Диапазон на
VPIP `v` — верхние `v%` комбинаций по порядку силы из `preflop.py`.
Вложенность диапазонов следует из конструкции: больший процент берёт
префикс того же списка.

Модель приблизительна и это признано: реальные диапазоны не упорядочены
по эквити против случайной руки — коннекторы в них весят больше, чем даёт
такая сортировка. Калибровка вынесена в открытые вопросы спеки. Отдельно
см. `preflop.py`: состав диапазона у самой отсечки — артефакт стабильной
сортировки при почти-ничьих, а не результат расчёта.
"""

from __future__ import annotations

from ._checks import check_non_negative
from .preflop import preflop_order
from .ranges import parse_range

TOTAL_COMBOS = 1326  # C(52, 2)

# Калибровочные параметры. Меняются по мере накопления наблюдений;
# ни один из них не является результатом расчёта.
DEFAULT_VPIP = 25.0
MIN_VPIP_HANDS = 30


def range_for_vpip(vpip: float | None, hands: int | None) -> tuple[list[str], bool]:
    """Комбинации диапазона и признак того, что взят дефолт.

    Второй элемент истинен, когда VPIP отсутствует, посчитан по выборке
    меньше `MIN_VPIP_HANDS` или пришёл с размером выборки, который не
    сравним с порогом (`None`, `NaN`): процент без внятного числа раздач
    ничем не подтверждён.
    Бейдж `0` у только что подсевшего игрока не означает нита, и вывод
    обязан это помечать.

    Диапазон минимально покрывающий: классы берутся сверху, пока их
    суммарный объём не достигнет цели, поэтому результат превышает цель
    не более чем на один класс (12 комбинаций). Пустым он не бывает
    никогда — даже на VPIP 0 соперник держит карты, а нулевой диапазон
    сломал бы любой расчёт эквити против него.
    """
    if vpip is not None and not 0 <= vpip <= 100:
        raise ValueError(f"VPIP вне диапазона 0..100: {vpip}")
    if hands is not None:
        check_non_negative(hands, "число раздач")

    # `not hands >= ...`, а не `hands < ...`: NaN проваливает оба сравнения,
    # и выборку неизвестного размера полагается считать недостаточной.
    used_default = vpip is None or hands is None or not hands >= MIN_VPIP_HANDS
    value = DEFAULT_VPIP if used_default else float(vpip)

    target = TOTAL_COMBOS * value / 100
    combos: set[str] = set()
    for entry in preflop_order():
        combos |= set(parse_range(entry["hand"]))
        if len(combos) >= target:
            break

    return sorted(combos), used_default
