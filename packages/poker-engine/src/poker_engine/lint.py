"""Линтер чисел ответа тренера (спека тренера §9).

Спека скиллпака §9: любое число в тексте обязано иметь след до вызова `poker-engine`. След —
числа печати фактов (`display`) всех шагов файла раздачи и номера шагов `1..N`; число текста без
следа модель вписала сама — линтер его называет, а тренер чинит текст, а не факты.

Число — `\\d+([.,]\\d+)?`: запятая читается как точка, знак отбрасывается, сравнение — строкой
после этого: `2.0` и `2` — разные числа (тренер переписывает печать, а не округляет). Не числа:
всё в обратных кавычках; позиция с цифрой (`UTG1`, `UTG+1`); `N-бет`, `N-bet`, `N-max`; записи
рук и комбинаций (`77`, `A5s`, `T9o`, `AhKd`) без единицы рядом — со знаком `%`, `BB` или `$`
рядом это всегда число (`77%`, `77 BB`, `$77`). Печать фактов читается тем же правилом, что
текст: `1` из `UTG+1` в печати линии следом не становится.
"""

from __future__ import annotations

import re

_RANK = "[2-9TJQKA]"
# Класс — старшей картой вперёд, как его печатает движок (`preflop.hand_classes`): `98s`, `T9o`,
# `K9`. `9T`, `25s` и `5K` (тысячи фишек) — не записи рук, цифры в них — числа.
_DESCENDING = "(?:" + "|".join(f"{high}[2-{int(high) - 1}]" for high in "3456789") + ")"
# Рука — комбинация, пара или класс, отдельным словом: не после `$` и не начало дроби (`77.5`);
# хвост дроби (`0.77`) съедает ветвь числа раньше. Числом читается только пара — из одних цифр,
# поэтому `%`, `BB` или `$` рядом делает числом её (`77 BB`, `77 $`, `$ 77`), а `A5s BB` остаётся
# рукой. «Рядом» — через любой пробел: перенос строки в Markdown рендерится пробелом.
_HAND = (
    r"(?<![\w$])(?<!\$\s)"
    rf"(?:{_RANK}[shdc]{_RANK}[shdc]"
    r"|(?P<pair>[2-9])(?P=pair)(?!\s*(?:%|\$|(?i:bb)))"
    rf"|[TJQKA]{_RANK}[so]|{_DESCENDING}[so]|[TJQKA][2-9])"
    r"(?!\w)(?![.,]\d)"
)
# Порядок ветвей — приоритет: в каждой точке текста первая подошедшая ветвь съедает своё.
_TOKEN = re.compile(
    r"(?P<quoted>`[^`]*`)"
    r"|(?P<position>\bUTG\+?\d\b)"
    r"|(?P<named>\b\d+-(?i:бет|bet|max))"
    rf"|(?P<hand>{_HAND})"
    r"|(?P<number>\d+(?:[.,]\d+)?)"
)


def numbers(text: str) -> list[str]:
    """Числа текста по порядку, запятая — точкой; не числа §9 пропущены."""
    return [
        match["number"].replace(",", ".")
        for match in _TOKEN.finditer(text)
        if match["number"] is not None
    ]


def untraced(text: str, facts: list[dict], steps: int) -> list[str]:
    """Числа текста без следа — по одному разу, в порядке первого появления.

    След — числа `display` фактов `facts` и номера шагов `1..steps`.
    """
    trace = {str(number) for number in range(1, steps + 1)}
    for item in facts:
        trace.update(numbers(item["display"]))
    return list(dict.fromkeys(number for number in numbers(text) if number not in trace))
